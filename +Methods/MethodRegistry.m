        end

        function methods = list(task, varargin)
            parser = inputParser;
            addParameter(parser, 'RunnableOnly', false, ...
                @(value) islogical(value) && isscalar(value));
            parse(parser, varargin{:});

            methods = Methods.MethodRegistry.catalog();
            task = string(task);
            keep = [methods.task] == task;
            if parser.Results.RunnableOnly
                keep = keep & [methods.runnable];
            end
            methods = methods(keep);
        end

        function method = find(id)
            methods = Methods.MethodRegistry.catalog();
            index = find([methods.id] == string(id), 1);
            if isempty(index)
                error('Methods:MethodRegistry:UnknownMethod', ...
                    'Unknown method registry ID: %s', char(string(id)));
            end
            method = methods(index);
        end

        function [items, ids] = uiChoices(task)
            methods = Methods.MethodRegistry.list(task, 'RunnableOnly', true);
            items = cellstr([methods.name]);
            ids = cellstr([methods.id]);
        end

        function text = evidence(id)
            method = Methods.MethodRegistry.find(id);
            text = char(method.evidence);
        end
    end

    methods (Static, Access = private)
        function value = entry(id, task, name, status, runnable, input_contract, output_contract, evidence)
            value = struct( ...
                'id', string(id), ...
                'task', string(task), ...
                'name', string(name), ...
                'status', string(status), ...
                'runnable', logical(runnable), ...
                'input_contract', string(input_contract), ...
                'output_contract', string(output_contract), ...
                'evidence', string(evidence));
        end
    end
end
