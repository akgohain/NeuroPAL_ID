classdef MethodRegistry
    %METHODREGISTRY Product-facing catalog of detection and identity methods.
    %
    % Benchmark experiments change faster than the desktop application. This
    % registry is the stable boundary: only runnable entries are offered in
    % the UI, while scaffolded entries retain their contracts and evidence for
    % the next adapter without pretending that they are available.

    methods (Static)
        function methods = catalog()
            methods = [ ...
                Methods.MethodRegistry.entry( ...
                    "mp", "detection", "Matching pursuit", "legacy", true, ...
                    "volume_rgbw", "centroids_yxz", ...
                    "Fast MATLAB baseline; useful when Python models are unavailable."), ...
                Methods.MethodRegistry.entry( ...
                    "nn", "detection", "Neural network", "legacy", true, ...
                    "volume_rgbw", "centroids_yxz", ...
                    "Bundled legacy neural detector."), ...
                Methods.MethodRegistry.entry( ...
                    "cellpose", "detection", "Cellpose", "adapter", true, ...
                    "volume_rgbw", "centroids_yxz_and_masks", ...
                    "Runnable when a compatible local Cellpose model is configured."), ...
                Methods.MethodRegistry.entry( ...
                    "yolo", "detection", "YOLO", "recommended_portable", true, ...
                    "volume_rgbw", "centroids_yxz_and_box_summary", ...
                    "Portable benchmarked detector; held-out F1@5um 0.7117."), ...
                Methods.MethodRegistry.entry( ...
                    "spotiflow_supervised", "detection", "Spotiflow", "recommended_portable", true, ...
                    "volume_rgbw", "centroids_xyz_with_scores", ...
                    "Frozen four-view detector; validation mean F1@3/6um 0.9233."), ...
