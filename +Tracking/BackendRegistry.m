classdef BackendRegistry
    %BACKENDREGISTRY Stable product catalog for video-tracking backends.

    methods (Static)
        function backends = catalog()
            backends = [ ...
                Tracking.BackendRegistry.entry( ...
                    "zephir", "ZephIR", "integrated", true, false, ...
                    "Sparse reference annotations; existing MATLAB/Python workflow."), ...
                Tracking.BackendRegistry.entry( ...
                    "ultrack", "Ultrack", "contract_ready", false, true, ...
                    "Backend-neutral contract ready; worker and segmentation cache remain."), ...
                Tracking.BackendRegistry.entry( ...
                    "hoct", "Higher-Order Transformer", "contract_ready", false, true, ...
                    "Backend-neutral contract ready; worker, weights, and segmentation cache remain.")];
        end

        function backend = find(id)
            backends = Tracking.BackendRegistry.catalog();
            index = find([backends.id] == lower(string(id)), 1);
            if isempty(index)
                error('Tracking:BackendRegistry:UnknownBackend', ...
                    'Unknown tracking backend: %s', char(string(id)));
            end
            backend = backends(index);
        end

        function [names, ids] = uiChoices()
            backends = Tracking.BackendRegistry.catalog();
            names = cellstr([backends.name]);
            ids = cellstr([backends.id]);
        end

        function readiness = inspect(id)
            backend = Tracking.BackendRegistry.find(id);
            readiness = struct( ...
                'backend', char(backend.id), ...
                'ready', backend.runnable, ...
                'summary', '', ...
                'runtime', '');
            if backend.runnable
                report=Runtime.Resolver.inspect(char(backend.id));
                readiness.ready=report.ready; readiness.summary=report.summary;
                readiness.runtime=report.profile.python;
            else
                readiness.ready=false;
                readiness.summary=sprintf('%s is not implemented in this application.',char(backend.name));
            end
        end
    end

    methods (Static, Access = private)
        function value = entry(id, name, status, runnable, requires_segmentation, summary)
            value = struct( ...
                'id', lower(string(id)), ...
                'name', string(name), ...
                'status', string(status), ...
                'runnable', logical(runnable), ...
                'requires_segmentation', logical(requires_segmentation), ...
                'summary', string(summary));
        end
    end
end
